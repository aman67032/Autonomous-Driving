function [scenario, egoVehicle] = scenario1_village_road()
    % SCENARIO1_VILLAGE_ROAD Scenario 1: Narrow Village Road with Mixed Traffic
    % Models an unmarked 6m rural Indian carriageway (Left-Hand Drive).
    % Ego (left lane y=+1.5m) encounters a slow bicycle ahead and an oncoming
    % truck (right lane y=-1.2m). The narrow road forces Ego to yield behind the
    % bicycle until the truck passes, then overtake. Further ahead, a stray cow
    % crosses perpendicularly and potholes require lateral avoidance.
    
    cfg = scenarioConfig();
    scenario = drivingScenario('StopTime', 30, 'SampleTime', 0.1);

    % Road: 200m long, 6m wide (Left lane: y in [0, 3], Right lane: y in [-3, 0])
    roadCenters = [0 0 0; 200 0 0];
    road(scenario, roadCenters, 6);

    % Ego vehicle starting in left lane at [0, 1.5, 0] at 8 m/s
    egoVehicle = vehicle(scenario, 'ClassID', cfg.classes.CAR, ...
        'Position', [0 1.5 0], 'Velocity', [8 0 0], 'Name', 'Ego');
    trajectory(egoVehicle, [0 1.5 0; 200 1.5 0], 8);

    % 1 Bicycle ahead in left lane (speed 3 m/s)
    bicycle = actor(scenario, 'ClassID', cfg.classes.BICYCLE, ...
        'Length', cfg.dimensions.BICYCLE(1), 'Width', cfg.dimensions.BICYCLE(2), ...
        'Height', cfg.dimensions.BICYCLE(3), 'Position', [35 1.8 0], ...
        'Velocity', [3 0 0], 'Name', 'Bicycle');
    trajectory(bicycle, [35 1.8 0; 200 1.8 0], 3);

    % 1 Oncoming heavy truck (speed 10 m/s, width=2.5m) in right lane
    % Extends past x = -50m so it doesn't park in road
    truck = vehicle(scenario, 'ClassID', cfg.classes.TRUCK, ...
        'Length', cfg.dimensions.TRUCK(1), 'Width', cfg.dimensions.TRUCK(2), ...
        'Height', cfg.dimensions.TRUCK(3), 'Position', [160 -1.2 0], ...
        'Velocity', [-10 0 0], 'Yaw', 180, 'Name', 'OncomingTruck');
    trajectory(truck, [160 -1.2 0; -60 -1.2 0], 10);

    % Stray Cow crossing perpendicularly from left field (y=+6m) to right field (y=-5m)
    % Crossing at x = 85m. Crosses at 1.0 m/s. Reaches lane center y=+1.5m at t ~ 8.5s
    cow = actor(scenario, 'ClassID', cfg.classes.CATTLE, ...
        'Length', cfg.dimensions.CATTLE(1), 'Width', cfg.dimensions.CATTLE(2), ...
        'Height', cfg.dimensions.CATTLE(3), 'Position', [85 6.0 0], ...
        'Velocity', [0 -1.0 0], 'Yaw', -90, 'Name', 'Cow');
    trajectory(cow, [85 6.0 0; 85 -5.0 0], 1.0);

    % Pedestrians walking on the left unpaved shoulder
    actor(scenario, 'ClassID', cfg.classes.PEDESTRIAN, ...
        'Length', cfg.dimensions.PEDESTRIAN(1), 'Width', cfg.dimensions.PEDESTRIAN(2), ...
        'Height', cfg.dimensions.PEDESTRIAN(3), 'Position', [60 3.5 0], ...
        'Velocity', [0.6 0 0], 'Name', 'Ped1');
    actor(scenario, 'ClassID', cfg.classes.PEDESTRIAN, ...
        'Length', cfg.dimensions.PEDESTRIAN(1), 'Width', cfg.dimensions.PEDESTRIAN(2), ...
        'Height', cfg.dimensions.PEDESTRIAN(3), 'Position', [65 3.8 0], ...
        'Velocity', [0.5 0 0], 'Name', 'Ped2');

    % Deep potholes requiring evasive steering (marked as hazards)
    actor(scenario, 'ClassID', cfg.classes.HAZARD, ...
        'Length', 1.5, 'Width', 1.2, 'Height', 0.3, ...
        'Position', [120 1.2 0], 'Name', 'Pothole1');
    actor(scenario, 'ClassID', cfg.classes.HAZARD, ...
        'Length', 1.5, 'Width', 1.2, 'Height', 0.3, ...
        'Position', [135 2.0 0], 'Name', 'Pothole2');
end
